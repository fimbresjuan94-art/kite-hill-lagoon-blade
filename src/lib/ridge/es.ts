export function readCorralLang(): "en" | "es" {
  try {
    const saved = localStorage.getItem("cds-lang");
    if (saved === "en" || saved === "es") return saved;
  } catch {
    /* private mode still gets Spanish */
  }
  return "es";
}

export function writeCorralLang(lang: "en" | "es") {
  try {
    localStorage.setItem("cds-lang", lang);
  } catch {
    /* the button still switches this tab */
  }
  document.documentElement.lang = lang;
}
